"""Runs the official Drama 3 on the CPU in float32 and saves the tensors the C++ port is checked against.

Usage: uv run python dump.py OUT --reference REF.wav --reference-text TEXT [--frames N] [--seed S]
                             [--temperature T] [--top-p P] [--top-k K] TEXT

It speaks TEXT with one reference as fish-speech's server does, through the official functions: the reference encoded
by TTSInferenceEngine.load_references(), the seed set by set_seed(), the prompt built by build_drama3_prompt(), at
most N frames generated by generate_drama3(), and the frames decoded by the codec. Hooks on the official modules save
what they computed. The sampling settings default to the model card's, which SGLang-Omni also takes. The model takes
about 49 GB of memory (official.py), and a frame about 1.7 s on 8 cores (Modal, 2026-10-15). It writes OUT/*.npy and
meta.json:

  reference_audio    the reference as the codec encodes it, mono at 44.1 kHz after fish-speech's resampling, [samples]
  codec_encoder_N    the output of the codec encoder's block N for the reference, [channels, time]
  codec_downsample   the quantizer's downsampling of the encoder's output, [1024, frames]
  codec_pre_module   the transformer before the quantizer, [1024, frames]
  reference_codes    the codes of the reference, [10, frames]: the semantic code, then the 9 residual codes
  prompt             the prompt's rows, [rows, 11]: a text row is [token, 0 x 10], an audio row
                     [code 0 + the first semantic id, codes 0..9]
  backbone_input     the backbone's input rows: the prompt's, then each generated frame's but the last,
                     [rows + frames - 1, 2048]
  backbone_layers    the residual stream after each of the 40 layers, [40, rows + frames - 1, 2048]
  backbone_mixer     the gated attention or Gated DeltaNet output of each layer, [40, rows + frames - 1, 2048]
  backbone_router    the router's logits of each layer, [40, rows + frames - 1, 256]
  backbone_moe       the experts' and the shared expert's output of each layer, [40, rows + frames - 1, 2048]
  backbone_hidden    the final norm's output, [rows + frames - 1, 2048]
  delta_state        each Gated DeltaNet layer's recurrent state after the prompt, [30, 32, 128, 128]
  conv_state         each Gated DeltaNet layer's convolution state after the prompt, [30, 8192, 3]
  main_candidates    the ids the main token is drawn from, the end id and the semantic ids in order, [4097]
  main_logits        the logits of those ids from the prompt's last row and each generated frame, [frames, 4097]
  tower_prefill      the tower's output after each of its 13 layers for the prompt's rows but the last, each row
                     labelled with the next, [13, rows - 1, 2048]
  tower_layers       the tower's output after each of its 13 layers for each generated frame, [frames, 13, 2048]
  head_logits        the 9 codebook heads' logits of each generated frame, [frames, 9, 4096]
  frames             the generated frames, [frames, 11], without the end
  codec_quantized    the sum of the codebooks' vectors of the frames' codes, [1024, frames]
  codec_post_module  the transformer after the quantizer, [1024, frames]
  codec_upsample     the quantizer's upsampling, [1024, frames x 4]
  codec_decoder_N    the output of the codec decoder's block N, [channels, time]
  audio              the decoded audio, [samples]
"""

import argparse
import hashlib
import json
import os

import numpy as np
import torch

from fish_speech.models.text2semantic.fish_omni.chunking import split_drama3_text
from fish_speech.models.text2semantic.fish_omni.generate import build_drama3_prompt, generate_drama3
from fish_speech.utils import set_seed
from fish_speech.utils.schema import ServeReferenceAudio, ServeTTSRequest

import official
import pins

MODEL_CARD_SAMPLING = {"temperature": 1.0, "top_p": 0.9, "top_k": 30}


def array(tensor):
    """A copy of `tensor` as float32. Without the copy, the array shares the memory of a float32 tensor on the CPU, and a
    dump on Modal's Linux read the audio decoder's prompt outputs of layers 3 to 5 back as other values and zeros
    (2026-10-15)."""
    return tensor.detach().to("cpu", torch.float32, copy=True).numpy()


class Recorder:
    """Keeps what hooks on the official modules saw, by name, in the order the modules ran."""

    def __init__(self):
        self.saved = {}
        self.handles = []

    def add(self, name, value):
        self.saved.setdefault(name, []).append(value)

    def output(self, module, name, transform=lambda output: output):
        self.handles.append(module.register_forward_hook(lambda m, args, output: self.add(name, array(transform(output)))))

    def remove(self):
        for handle in self.handles:
            handle.remove()
        self.handles.clear()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("out")
    parser.add_argument("text")
    parser.add_argument("--reference", required=True)
    parser.add_argument("--reference-text", required=True)
    parser.add_argument("--frames", type=int, default=24)
    parser.add_argument("--seed", type=int, default=1)
    for name, value in MODEL_CARD_SAMPLING.items():
        parser.add_argument(f"--{name.replace('_', '-')}", type=type(value), default=value)
    args = parser.parse_args()
    if split_drama3_text(args.text) not in ([], [args.text]):
        raise SystemExit("the text is more than one of fish-speech's chunks; give a shorter one")
    os.makedirs(args.out, exist_ok=True)

    model, engine = official.engine()
    codec, backbone, tower = engine.decoder_model, model.backbone, model.audio_decoder
    out = {}

    # The reference, through the server's own loading and encoding.
    record = Recorder()
    for index, block in enumerate(codec.encoder.block):
        record.output(block, f"codec_encoder_{index}", lambda o: o[0])
    record.output(codec.quantizer.downsample, "codec_downsample", lambda o: o[0])
    record.output(codec.quantizer.pre_module, "codec_pre_module", lambda o: o[0])
    load_audio = engine.load_audio
    engine.load_audio = lambda audio, rate: record.add("reference_audio", load_audio(audio, rate)) or record.saved["reference_audio"][-1]
    with open(args.reference, "rb") as f:
        reference_bytes = f.read()
    request = ServeTTSRequest(text=args.text, references=[ServeReferenceAudio(audio=reference_bytes, text=args.reference_text)])
    prompt_tokens, prompt_texts = engine.load_references(request)
    engine.load_audio = load_audio
    record.remove()
    out.update({name: values[0] for name, values in record.saved.items()})
    out["reference_codes"] = prompt_tokens[0].numpy().astype(np.int32)

    prompt = build_drama3_prompt(args.text, model.tokenizer, model.config, prompt_texts, prompt_tokens)
    out["prompt"] = prompt.numpy().astype(np.int32)

    # The generation, with every module the C++ port computes hooked.
    record = Recorder()
    layers = backbone.model.layers
    record.handles.append(backbone.register_forward_pre_hook(
        lambda m, args, kwargs: record.add("backbone_input", array(kwargs["inputs_embeds"][0])), with_kwargs=True))
    record.output(backbone, "backbone_hidden", lambda o: o[0])
    for layer in layers:
        mixer = layer.self_attn if layer.layer_type == "full_attention" else layer.linear_attn
        record.output(layer, "backbone_layers", lambda o: o[0])
        record.output(mixer, "backbone_mixer", lambda o: o[0])
        record.output(layer.mlp.gate, "backbone_router")
        record.output(layer.mlp, "backbone_moe", lambda o: o[0])
    delta_layers = [layer.linear_attn for layer in layers if layer.layer_type != "full_attention"]

    # The prefill runs the prompt in chunks of 128 rows, the last of which may be one row as a decode step is, so the
    # state is taken after the call whose rows end at the prompt's last position.
    def after_prompt(module, args, kwargs, output):
        if int(kwargs["input_pos"][-1]) == len(prompt) - 1:
            record.add("delta_state", np.stack([array(d.recurrent_state[0]) for d in delta_layers]))
            record.add("conv_state", np.stack([array(d.conv_state[0]) for d in delta_layers]))

    record.handles.append(backbone.register_forward_hook(after_prompt, with_kwargs=True))
    tower_layers = [*tower.shared_layers, *tower.residual_layers]
    phase = {"name": None}
    for layer in tower_layers:
        record.handles.append(layer.register_forward_hook(lambda m, a, o: record.add(f"tower_{phase['name']}", array(o))))
    for head in tower.codebook_heads:
        record.output(head, "head_logits", lambda o: o[0])
    prefill, decode_step = tower.prefill, tower.decode_step

    def prefill_hooked(*a, **k):
        phase["name"] = "prefill"
        return prefill(*a, **k)

    def decode_step_hooked(logits, *a, **k):
        phase["name"] = "layers"
        sampled = decode_step(logits, *a, **k)
        record.add("main_logits", array(logits[0, tower.main_candidates]))
        return sampled

    tower.prefill, tower.decode_step = prefill_hooked, decode_step_hooked
    set_seed(args.seed)
    frames, finish = generate_drama3(model, prompt, max_new_tokens=args.frames, temperature=args.temperature,
                                     top_k=args.top_k, top_p=args.top_p)
    tower.prefill, tower.decode_step = prefill, decode_step
    record.remove()
    saved = record.saved
    out["frames"] = frames.numpy().astype(np.int32)
    out["main_candidates"] = tower.main_candidates.numpy().astype(np.int32)
    out["main_logits"] = np.stack(saved["main_logits"])
    for name in ("backbone_input", "backbone_hidden"):
        out[name] = np.concatenate(saved[name])
    for name in ("backbone_layers", "backbone_mixer", "backbone_router", "backbone_moe"):
        calls = saved[name]
        out[name] = np.stack([np.concatenate(calls[index::len(layers)]) for index in range(len(layers))])
    out["delta_state"], out["conv_state"] = saved["delta_state"][0], saved["conv_state"][0]
    count = len(tower_layers)
    prefill_calls = saved["tower_prefill"]
    out["tower_prefill"] = np.stack([np.concatenate(prefill_calls[index::count]) for index in range(count)])
    out["tower_layers"] = np.stack(saved["tower_layers"]).reshape(-1, count, saved["tower_layers"][0].shape[-1])
    heads = len(tower.codebook_heads)
    out["head_logits"] = np.stack(saved["head_logits"]).reshape(-1, heads, saved["head_logits"][0].shape[-1])

    # The frames' codes decoded, as the server decodes each chunk.
    record = Recorder()
    record.handles.append(codec.quantizer.post_module.register_forward_pre_hook(
        lambda m, a: record.add("codec_quantized", array(a[0][0]))))
    record.output(codec.quantizer.post_module, "codec_post_module", lambda o: o[0])
    record.output(codec.quantizer.upsample, "codec_upsample", lambda o: o[0])
    for index, block in enumerate(codec.decoder.model):
        record.output(block, f"codec_decoder_{index}", lambda o: o[0])
    with torch.inference_mode():
        audio = engine.get_audio_segment(type("Result", (), {"codes": frames[:, 1:].T.contiguous()})())
    record.remove()
    out.update({name: values[0] for name, values in record.saved.items()})
    out["audio"] = np.asarray(audio, dtype=np.float32)

    lengths = {"rows": len(prompt), "frames": len(frames), "reference_frames": int(prompt_tokens[0].shape[1])}
    expected = {"backbone_input": lengths["rows"] + lengths["frames"] - (finish != "eos"),
                "main_logits": lengths["frames"] + (finish == "eos")}
    for name, rows in expected.items():
        if out[name].shape[0] != rows:
            raise SystemExit(f"{name} has {out[name].shape[0]} rows, not {rows}; the hooks missed a call")
    for name, value in out.items():
        np.save(os.path.join(args.out, f"{name}.npy"), value)
    meta = {
        "code": pins.CODE,
        "model": {"repository": pins.MODEL["repository"], "revision": pins.MODEL["revision"]},
        "text": args.text,
        "reference": {"file": os.path.basename(args.reference), "sha256": hashlib.sha256(reference_bytes).hexdigest(),
                      "text": args.reference_text, "prompt_text": prompt_texts[0]},
        "seed": args.seed,
        "sampling": {"temperature": args.temperature, "top_p": args.top_p, "top_k": args.top_k, "max_new_tokens": args.frames},
        "finish": finish,
        **lengths,
        "semantic_start_token_id": model.config.semantic_start_token_id,
        "eos_token_id": model.config.eos_token_id,
        "sample_rate": codec.sample_rate,
        "shapes": {name: list(value.shape) for name, value in out.items()},
    }
    with open(os.path.join(args.out, "meta.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=1)
    print(json.dumps({k: v for k, v in meta.items() if k != "shapes"}, ensure_ascii=False))


if __name__ == "__main__":
    main()
