"""Writes src/families/drama3/unicode.inc: the code point ranges of the characters that fish-speech's chunking tests
with Python, from the Unicode of the Python that runs fish-speech: those str.isdigit() accepts, which keep a decimal
such as 3.14 in one piece, and those the regular expression \\w matches, which end the name of a pair of tags.

usage: uv run python gen_unicode.py ../../src/families/drama3/unicode.inc
"""

import re
import sys
import unicodedata


def ranges(accept):
    out, start = [], None
    for cp in range(0x110001):
        inside = cp < 0x110000 and accept(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name, rs):
    return f"static const CodepointRange {name}[] = {{\n" + ",\n".join("    {0x%X, 0x%X}" % r for r in rs) + "\n};\n"


word = re.compile(r"\w")
digits = ranges(str.isdigit)
words = ranges(lambda c: word.fullmatch(c) is not None)
with open(sys.argv[1], "w") as f:
    f.write(f"// Generated by reference/drama3/gen_unicode.py from Python {sys.version.split()[0]}'s Unicode {unicodedata.unidata_version}.\n")
    f.write(emit("kDigits", digits))
    f.write(emit("kWordCharacters", words))
print(len(digits), len(words))
